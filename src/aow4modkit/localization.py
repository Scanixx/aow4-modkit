"""UTF-8 GNU MO output for simple singular messages (no plural/context API yet)."""
import struct
from .errors import ValidationError


def compile_messages(messages: dict[str, str], language="en") -> bytes:
    if "" in messages or any(not isinstance(k, str) or not isinstance(v, str) for k, v in messages.items()):
        raise ValidationError("Messages must be string pairs; the MO header key is generated by ModKit")
    if any("\x00" in k or "\x00" in v for k, v in messages.items()):
        raise ValidationError("Plural/context message encoding is not supported in this first API")
    entries = sorted({"": f"Content-Type: text/plain; charset=UTF-8\nLanguage: {language}\n", **messages}.items())
    count = len(entries)
    start = 28 + 16 * count
    originals, translations, original_table, translation_table = bytearray(), bytearray(), [], []
    for key, value in entries:
        k, v = key.encode("utf-8"), value.encode("utf-8")
        original_table.append((len(k), start + len(originals)))
        translation_table.append((len(v), len(translations)))
        originals.extend(k + b"\x00")
        translations.extend(v + b"\x00")
    translation_start = start + len(originals)
    return (struct.pack("<7I", 0x950412DE, 0, count, 28, 28 + 8 * count, 0, 0)
            + b"".join(struct.pack("<II", *row) for row in original_table)
            + b"".join(struct.pack("<II", length, translation_start + offset) for length, offset in translation_table)
            + originals + translations)
